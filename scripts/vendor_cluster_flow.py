"""Copy the PhysicsEngine Cosmic Flow lab (cosmic_view) into native/cluster_flow/vendor.

The cosmic_flow library, shaders and camera motion are copied unchanged.
``apps/cosmic/main.cpp`` becomes ``cosmic_core.hpp``: the same code without the
command-line parser, the ImGui style and slider helpers, ``run()`` (the GLFW
window loop and ImGui panel) and ``main()``. The worker thread, baking, controls
and the lab's own worker self-test stay, so CAst's bridge
(native/cluster_flow/cast_cluster_flow.cpp) drives them directly.
``control_help.hpp`` keeps the lab's tooltip text without its ImGui wrappers.

Usage: python scripts/vendor_cluster_flow.py [path\\to\\PhysicsEngine]
"""

from __future__ import annotations

import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from vendor_galaxy_merger import _block_end  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "native" / "cluster_flow" / "vendor"
LIBRARY = (
    "src/cosmic/cluster_field.hpp",
    "src/cosmic/cosmology.cpp",
    "src/cosmic/cosmology.hpp",
    "src/cosmic/flow.cpp",
    "src/cosmic/flow.hpp",
    "src/cosmic/recording.cpp",
    "src/cosmic/recording.hpp",
    "src/cosmic/types.hpp",
    "apps/cosmic/camera_motion.hpp",
    "apps/cosmic/shaders.hpp",
    "apps/viewer/gl_loader.cpp",
    "apps/viewer/gl_loader.hpp",
    "third_party/stb_image_write.h",
)
# frame_export carries CAst's ffmpeg override; reuse the Black Hole copy.
CAST_FRAME_EXPORT = ROOT / "native" / "blackhole" / "vendor" / "apps" / "viewer"
# Top-level definitions that belong to the command line or the ImGui/GLFW front end.
REMOVED = (
    "int integer(",
    "float real(",
    "Options parse(",
    "void style(",
    "bool slider(",
    "float readScale(",
    "int run(",
    "int main(",
)
REMOVED_LINES = (
    "#include <GLFW/glfw3.h>",
    "#include <imgui.h>",
    "#include <imgui_impl_glfw.h>",
    "#include <imgui_impl_opengl3.h>",
)
FRONT_END = ("ImGui", "imgui", "glfw", "GLFW", "int main(")


def strip_core(source: str) -> str:
    lines = source.splitlines()
    out: list[str] = []
    index = 0
    removed: set[str] = set()
    while index < len(lines):
        line = lines[index]
        if line.strip() in REMOVED_LINES:
            removed.add(line.strip())
            index += 1
            continue
        match = next((prefix for prefix in REMOVED if line.startswith(prefix)), None)
        if match is not None:
            removed.add(match)
            index = _block_end(lines, index) + 1
            continue
        out.append(line)
        index += 1
    missing = [prefix for prefix in REMOVED + REMOVED_LINES if prefix not in removed]
    if missing:
        raise ValueError(f"cosmic_view layout changed; not found: {missing}")
    leftover = [n + 1 for n, text in enumerate(out) if any(token in text for token in FRONT_END)]
    if leftover:
        raise ValueError(f"front-end code left on cosmic_core lines {leftover}")
    header = (
        "// Generated by scripts/vendor_cluster_flow.py from PhysicsEngine apps/cosmic/main.cpp.\n"
        "// The lab's code without its command line, ImGui panel, GLFW window loop (run) and\n"
        "// main(); CAst's Qt panel replaces them. Included once, by\n"
        "// native/cluster_flow/cast_cluster_flow.cpp.\n"
        "#pragma once\n"
    )
    return header + "\n".join(out) + "\n"


def strip_help(source: str) -> str:
    lines = [line for line in source.splitlines() if line.strip() != "#include <imgui.h>"]
    start = next((n for n, line in enumerate(lines) if line.startswith("inline void hint(")), None)
    end = max((n for n, line in enumerate(lines) if line == "}"), default=None)
    if start is None or end is None or end < start:
        raise ValueError("control_help.hpp layout changed")
    out = lines[:start] + lines[end:]
    if any("ImGui" in line for line in out):
        raise ValueError("ImGui code left in control_help.hpp")
    header = (
        "// Generated by scripts/vendor_cluster_flow.py from PhysicsEngine apps/cosmic/control_help.hpp:\n"
        "// the lab's tooltip text, without its ImGui widget wrappers.\n"
    )
    return header + "\n".join(out) + "\n"


def main() -> int:
    source = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT.parent / "PhysicsEngine"
    if not (source / "apps" / "cosmic" / "main.cpp").is_file():
        print(f"PhysicsEngine not found at {source}", file=sys.stderr)
        return 1
    for relative in LIBRARY:
        destination = TARGET / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source / relative, destination)
    viewer = TARGET / "apps" / "viewer"
    for name in ("frame_export.cpp", "frame_export.hpp"):
        shutil.copy2(CAST_FRAME_EXPORT / name, viewer / name)
    cosmic = TARGET / "apps" / "cosmic"
    core = strip_core((source / "apps" / "cosmic" / "main.cpp").read_text(encoding="utf-8"))
    (cosmic / "cosmic_core.hpp").write_text(core, encoding="utf-8", newline="\n")
    help_text = strip_help((source / "apps" / "cosmic" / "control_help.hpp").read_text(encoding="utf-8"))
    (cosmic / "control_help.hpp").write_text(help_text, encoding="utf-8", newline="\n")
    print(f"Vendored PhysicsEngine Cosmic Flow into {TARGET}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
